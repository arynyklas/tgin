//! Test-only: a seeded, schema-driven generator of valid TL for any
//! constructor, and grammers' typed (de)serializers as the oracle (ported
//! from the M3 spike's `tl_roundtrip.rs`).
//!
//! The generator writes valid TL straight from the schema. grammers turns
//! those bytes into its typed value and back ("typed bytes"); the property
//! tests compare tgin's codec and decoder with that.

use grammers_tl_types::deserialize::{Cursor, Error as DeError};
use grammers_tl_types::{Deserializable, Serializable};

use crate::decode::PeerId;
use crate::schema::{Kind, Schema, Ty, write_tl_bytes};

pub(crate) type DeResult<T> = Result<T, DeError>;

pub(crate) const SEED: u64 = 0x5eed_0000_0011_0005;
const MAX_DEPTH: u32 = 6;
const FUEL: u32 = 48;

/// The case count per constructor: `TGIN_TL_CASES` if set, else `default`.
pub(crate) fn cases(default: u32) -> u32 {
    std::env::var("TGIN_TL_CASES")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(default)
}

/// Stand-in for a generic function's `!X`: any function, read through
/// grammers' typed deserializer for that function and kept as its bytes.
pub(crate) struct AnyObject(Vec<u8>);

impl Deserializable for AnyObject {
    fn deserialize(buf: &mut Cursor<'_>) -> DeResult<Self> {
        let id = u32::deserialize(buf)?;
        match typed::function_body_api(id, buf) {
            Some(r) => r.map(AnyObject),
            None => Err(DeError::UnexpectedConstructor { id }),
        }
    }
}

impl Serializable for AnyObject {
    fn serialize(&self, buf: &mut impl Extend<u8>) {
        buf.extend(self.0.iter().copied());
    }
}

/// What grammers' typed struct holds in the fields `decode::facts` reads.
#[derive(Clone, Debug, Default)]
pub(crate) struct Oracle {
    pub pts: Option<i32>,
    pub pts_count: Option<i32>,
    pub qts: Option<i32>,
    pub channel_id: Option<i64>,
    pub chat_id: Option<i64>,
    pub user_id: Option<i64>,
    pub peer: Option<PeerId>,
    pub from: Option<PeerId>,
    pub from_user: Option<i64>,
    pub message: Option<MessageOracle>,
    pub text: Option<String>,
    pub out: Option<bool>,
    /// `updateShort`'s update, as grammers re-serializes it.
    pub inner: Option<Vec<u8>>,
}

#[derive(Clone, Debug, Default)]
pub(crate) struct MessageOracle {
    pub peer: Option<PeerId>,
    pub from: Option<PeerId>,
    pub text: Option<String>,
    pub out: bool,
}

/// A typed field → the oracle's view of it.
pub(crate) trait G<T> {
    fn g(&self) -> Option<T>;
}

impl G<i32> for i32 {
    fn g(&self) -> Option<i32> {
        Some(*self)
    }
}

impl G<i64> for i64 {
    fn g(&self) -> Option<i64> {
        Some(*self)
    }
}

impl G<bool> for bool {
    fn g(&self) -> Option<bool> {
        Some(*self)
    }
}

impl G<String> for String {
    fn g(&self) -> Option<String> {
        Some(self.clone())
    }
}

impl<T, X: G<T>> G<T> for Option<X> {
    fn g(&self) -> Option<T> {
        self.as_ref().and_then(G::g)
    }
}

impl<T, X: G<T>> G<T> for Box<X> {
    fn g(&self) -> Option<T> {
        (**self).g()
    }
}

impl G<PeerId> for grammers_tl_types::enums::Peer {
    fn g(&self) -> Option<PeerId> {
        use grammers_tl_types::enums::Peer;
        Some(match self {
            Peer::User(p) => PeerId::User(p.user_id),
            Peer::Chat(p) => PeerId::Chat(p.chat_id),
            Peer::Channel(p) => PeerId::Channel(p.channel_id),
        })
    }
}

impl G<MessageOracle> for grammers_tl_types::enums::Message {
    fn g(&self) -> Option<MessageOracle> {
        use grammers_tl_types::enums::Message;
        Some(match self {
            Message::Empty(m) => MessageOracle {
                peer: m.peer_id.g(),
                ..MessageOracle::default()
            },
            Message::Message(m) => MessageOracle {
                peer: m.peer_id.g(),
                from: m.from_id.g(),
                text: Some(m.message.clone()),
                out: m.out,
            },
            Message::Service(m) => MessageOracle {
                peer: m.peer_id.g(),
                from: m.from_id.g(),
                text: None,
                out: m.out,
            },
        })
    }
}

impl G<Vec<u8>> for grammers_tl_types::enums::Update {
    fn g(&self) -> Option<Vec<u8>> {
        Some(self.to_bytes())
    }
}

