/// SplitMix64.
pub(crate) struct Rng(pub u64);

impl Rng {
    pub(crate) fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }
    pub(crate) fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
    fn coin(&mut self) -> bool {
        self.next() & 1 == 1
    }
    fn fill(&mut self, b: &mut [u8]) {
        for x in b {
            *x = self.next() as u8;
        }
    }
}

/// Per type, the cheapest constructor, so a generator out of fuel ends.
pub(crate) struct Plan {
    pub cost: Vec<u32>,
    type_min: Vec<usize>,
    functions: Vec<usize>,
    fn_min: usize,
}

impl Plan {
    pub(crate) fn new(s: &Schema) -> Self {
        let functions: Vec<usize> = (0..s.ctors.len())
            .filter(|&i| s.ctors[i].ty.is_none())
            .collect();
        let min_of = |cost: &[u32], idxs: &mut dyn Iterator<Item = usize>| {
            idxs.map(|i| cost[i]).min().unwrap_or(u32::MAX)
        };
        let mut cost = vec![u32::MAX; s.ctors.len()];
        loop {
            let mut changed = false;
            for (i, c) in s.ctors.iter().enumerate() {
                let mut worst = 0u32;
                for p in c.params {
                    let Kind::Field { ty, flag: None } = &p.kind else {
                        continue;
                    };
                    let need = match ty {
                        Ty::Boxed(t) => min_of(
                            &cost,
                            &mut s.type_def(*t).ctors.iter().map(|&k| usize::from(k)),
                        ),
                        Ty::Bare(k) => cost[usize::from(*k)],
                        Ty::Any => min_of(&cost, &mut functions.iter().copied()),
                        _ => 0,
                    };
                    worst = worst.max(need);
                }
                let mine = worst.saturating_add(1);
                if mine < cost[i] {
                    cost[i] = mine;
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        let pick =
            |idxs: &mut dyn Iterator<Item = usize>| idxs.min_by_key(|&i| cost[i]).unwrap_or(0);
        let type_min = s
            .types
            .iter()
            .map(|t| pick(&mut t.ctors.iter().map(|&k| usize::from(k))))
            .collect();
        let fn_min = pick(&mut functions.iter().copied());
        Plan {
            cost,
            type_min,
            functions,
            fn_min,
        }
    }
}

#[derive(Default, Clone)]
pub(crate) struct Stats {
    pub cases: u64,
    pub bytes: u64,
    pub max_len: usize,
    pub flag_words_set: u64,
    pub flag_words_zero: u64,
    pub optional_present: u64,
    pub optional_absent: u64,
    pub true_set: u64,
    pub true_unset: u64,
    pub vectors_nonempty: u64,
    pub vectors_empty: u64,
    pub long_form_strings: u64,
    pub long_form_bytes: u64,
    pub invalid_utf8: u64,
    pub multibyte_utf8: u64,
    pub nonfinite_doubles: u64,
    pub negative_zero: u64,
    pub int128: u64,
    pub int256: u64,
    pub bools: u64,
    pub nested_objects: u64,
    pub generic_queries: u64,
    pub max_depth: u32,
    pub grammers_lossy_cases: u64,
}

impl Stats {
    pub(crate) fn add(&mut self, o: &Stats) {
        macro_rules! sum { ($($f:ident),*) => { $(self.$f += o.$f;)* } }
        sum!(
            cases,
            bytes,
            flag_words_set,
            flag_words_zero,
            optional_present,
            optional_absent,
            true_set,
            true_unset,
            vectors_nonempty,
            vectors_empty,
            long_form_strings,
            long_form_bytes,
            invalid_utf8,
            multibyte_utf8,
            nonfinite_doubles,
            negative_zero,
            int128,
            int256,
            bools,
            nested_objects,
            generic_queries,
            grammers_lossy_cases
        );
        self.max_len = self.max_len.max(o.max_len);
        self.max_depth = self.max_depth.max(o.max_depth);
    }
}

#[derive(Clone, Copy)]
pub(crate) enum FlagMode {
    Random,
    All,
    None,
}

impl FlagMode {
    /// The mode of case `case`: all flags, no flags, then random.
    pub(crate) fn of(case: u32) -> Self {
        match case % 8 {
            0 => Self::All,
            1 => Self::None,
            _ => Self::Random,
        }
    }
}

pub(crate) struct Gen<'a> {
    pub s: &'a Schema,
    pub plan: &'a Plan,
    pub rng: Rng,
    pub fuel: u32,
    pub mode: FlagMode,
    /// Only valid UTF-8 strings, so grammers holds every value losslessly.
    pub utf8_only: bool,
    /// Set when a string is not valid UTF-8 (grammers decodes it lossily).
    pub lossy: bool,
    pub st: &'a mut Stats,
}

impl<'a> Gen<'a> {
    pub(crate) fn new(
        s: &'a Schema,
        plan: &'a Plan,
        seed: u64,
        mode: FlagMode,
        st: &'a mut Stats,
    ) -> Self {
        Gen {
            s,
            plan,
            rng: Rng(seed),
            fuel: FUEL,
            mode,
            utf8_only: false,
            lossy: false,
            st,
        }
    }

    /// One value of constructor `idx`, its id first when `with_id`.
    pub(crate) fn ctor(&mut self, out: &mut Vec<u8>, idx: usize, with_id: bool, depth: u32) {
        let c = &self.s.ctors[idx];
        self.st.max_depth = self.st.max_depth.max(depth);
        if depth > 0 {
            self.st.nested_objects += 1;
        }
        if with_id {
            out.extend_from_slice(&c.id.to_le_bytes());
        }
        self.fuel = self.fuel.saturating_sub(1);
        let lean = self.fuel == 0 || depth >= MAX_DEPTH;
        let mut words = [0u32; crate::schema::MAX_FLAG_WORDS];
        for p in c.params {
            match &p.kind {
                Kind::Flags { slot, known } => {
                    let w = match (lean, self.mode) {
                        (true, _) | (false, FlagMode::None) => 0,
                        (false, FlagMode::All) => *known,
                        (false, FlagMode::Random) => known & self.rng.next() as u32,
                    };
                    if w == 0 {
                        self.st.flag_words_zero += 1;
                    } else {
                        self.st.flag_words_set += 1;
                    }
                    out.extend_from_slice(&w.to_le_bytes());
                    words[usize::from(*slot)] = w;
                }
                Kind::Field { ty, flag } => {
                    if let Some(f) = flag {
                        let set = words[usize::from(f.slot)] & (1 << f.bit) != 0;
                        match (ty, set) {
                            (Ty::True, true) => self.st.true_set += 1,
                            (Ty::True, false) => self.st.true_unset += 1,
                            (_, true) => self.st.optional_present += 1,
                            (_, false) => self.st.optional_absent += 1,
                        }
                        if !set {
                            continue;
                        }
                    }
                    self.value(out, ty, depth + 1, lean);
                }
            }
        }
    }

    fn len_class(&mut self) -> usize {
        match self.rng.below(16) {
            0..=2 => 0,
            3..=9 => self.rng.below(32) as usize,
            10..=12 => 248 + self.rng.below(12) as usize,
            13 | 14 => 254 + self.rng.below(400) as usize,
            _ => self.rng.below(254) as usize,
        }
    }

    fn string(&mut self) -> Vec<u8> {
        let target = self.len_class();
        match self.rng.below(10) {
            0 if target > 0 && !self.utf8_only => {
                self.lossy = true;
                self.st.invalid_utf8 += 1;
                let mut b = vec![0u8; target];
                self.rng.fill(&mut b);
                b[self.rng.below(target as u64) as usize] = 0xff;
                b
            }
            1..=3 => {
                self.st.multibyte_utf8 += 1;
                const CHARS: [char; 6] = ['ж', 'Ä', '中', '😀', '\u{fffd}', '\u{10ffff}'];
                let mut s = String::new();
                while s.len() < target {
                    s.push(CHARS[self.rng.below(6) as usize]);
                }
                s.into_bytes()
            }
            4 => {
                // A command-like text, for `facts`' `command`.
                const T: [&str; 4] = ["/start@my_bot payload", "/help", "/", "/x\ny"];
                T[self.rng.below(4) as usize].as_bytes().to_vec()
            }
            _ => {
                const ASCII: &[u8] = b"abcXYZ019 \"\\/\n\t\x00\x1f{}[]:,_-@";
                (0..target)
                    .map(|_| ASCII[self.rng.below(ASCII.len() as u64) as usize])
                    .collect()
            }
        }
    }

    pub(crate) fn value(&mut self, out: &mut Vec<u8>, ty: &Ty, depth: u32, lean: bool) {
        match ty {
            Ty::Int => {
                let v = match self.rng.below(8) {
                    0 => 0,
                    1 => -1,
                    2 => [i32::MIN, i32::MAX][self.rng.below(2) as usize],
                    _ => self.rng.next() as i32,
                };
                out.extend_from_slice(&v.to_le_bytes());
            }
            Ty::Long => {
                const EDGES: [i64; 6] = [i64::MIN, i64::MAX, (1 << 53) - 1, 1 << 53, -(1 << 53), 0];
                let v = match self.rng.below(4) {
                    0 => EDGES[self.rng.below(6) as usize],
                    _ => self.rng.next() as i64,
                };
                out.extend_from_slice(&v.to_le_bytes());
            }
            Ty::Double => {
                let bits = match self.rng.below(12) {
                    0 => 0x7ff0_0000_0000_0000 | (self.rng.next() & 0x000f_ffff_ffff_ffff) | 1,
                    1 => [f64::INFINITY, f64::NEG_INFINITY][self.rng.below(2) as usize].to_bits(),
                    2 => (-0.0f64).to_bits(),
                    3 => self.rng.next() & 0x800f_ffff_ffff_ffff,
                    4 => (self.rng.below(1 << 20) as f64).to_bits(),
                    _ => self.rng.next(),
                };
                let x = f64::from_bits(bits);
                if !x.is_finite() {
                    self.st.nonfinite_doubles += 1;
                }
                if bits == (-0.0f64).to_bits() {
                    self.st.negative_zero += 1;
                }
                out.extend_from_slice(&bits.to_le_bytes());
            }
            Ty::Str => {
                let b = self.string();
                if b.len() >= 254 {
                    self.st.long_form_strings += 1;
                }
                let _ = write_tl_bytes(out, &b);
            }
            Ty::Bytes => {
                let mut b = vec![0u8; self.len_class()];
                self.rng.fill(&mut b);
                if b.len() >= 254 {
                    self.st.long_form_bytes += 1;
                }
                let _ = write_tl_bytes(out, &b);
            }
            Ty::Int128 | Ty::Int256 => {
                let mut b = vec![0u8; if *ty == Ty::Int128 { 16 } else { 32 }];
                self.rng.fill(&mut b);
                if *ty == Ty::Int128 {
                    self.st.int128 += 1;
                } else {
                    self.st.int256 += 1;
                }
                out.extend_from_slice(&b);
            }
            Ty::Bool => {
                self.st.bools += 1;
                let id = if self.rng.coin() {
                    crate::schema::BOOL_TRUE
                } else {
                    crate::schema::BOOL_FALSE
                };
                out.extend_from_slice(&id.to_le_bytes());
            }
            Ty::True => {}
            Ty::Vector(t) | Ty::BareVector(t) => {
                if matches!(ty, Ty::Vector(_)) {
                    out.extend_from_slice(&crate::schema::VECTOR_ID.to_le_bytes());
                }
                let objects = matches!(t, Ty::Boxed(_) | Ty::Bare(_) | Ty::Any | Ty::Vector(_));
                let n = if lean {
                    0
                } else if objects {
                    self.rng.below(4)
                } else {
                    self.rng.below(7)
                };
                if n == 0 {
                    self.st.vectors_empty += 1;
                } else {
                    self.st.vectors_nonempty += 1;
                }
                out.extend_from_slice(&(n as i32).to_le_bytes());
                for _ in 0..n {
                    self.value(out, t, depth, lean);
                }
            }
            Ty::Boxed(t) => {
                let idx = if lean {
                    self.plan.type_min[usize::from(*t)]
                } else {
                    let v = self.s.type_def(*t).ctors;
                    usize::from(v[self.rng.below(v.len() as u64) as usize])
                };
                self.ctor(out, idx, true, depth);
            }
            Ty::Bare(c) => self.ctor(out, usize::from(*c), false, depth),
            Ty::Any => {
                self.st.generic_queries += 1;
                let idx = if lean {
                    self.plan.fn_min
                } else {
                    let f = &self.plan.functions;
                    f[self.rng.below(f.len() as u64) as usize]
                };
                self.ctor(out, idx, true, depth);
            }
        }
    }
}

pub(crate) fn hex(b: &[u8]) -> String {
    use std::fmt::Write as _;
    let mut s = String::with_capacity(b.len() * 2);
    for x in b {
        let _ = write!(s, "{x:02x}");
    }
    s
}

/// The seed of one case, from the constructor id and the case number.
pub(crate) fn seed(id: u32, case: u32) -> u64 {
    SEED ^ u64::from(id) << 24 ^ u64::from(case)
}

/// Runs `check(idx, case)` for every constructor index in `ctors` and
/// every case, over all cores; returns the findings, at most a few per
/// constructor.
pub(crate) fn par_each<F>(ctors: &[usize], check: F) -> Vec<String>
where
    F: Fn(usize, &mut Vec<String>) + Sync,
{
    use std::sync::Mutex;
    use std::sync::atomic::{AtomicUsize, Ordering};
    let next = AtomicUsize::new(0);
    let found = Mutex::new(Vec::new());
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|scope| {
        for _ in 0..threads {
            scope.spawn(|| {
                let mut mine = Vec::new();
                loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    let Some(&idx) = ctors.get(i) else { break };
                    check(idx, &mut mine);
                }
                if let Ok(mut f) = found.lock() {
                    f.extend(mine);
                }
            });
        }
    });
    found.into_inner().unwrap_or_else(|e| e.into_inner())
}
