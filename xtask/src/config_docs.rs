//! `docs/config-reference.md`: the config file's reference, rendered from
//! its JSON Schema, so that every description comes from the doc comments
//! of the config model (`crates/tgin-core/src/config/`).
//!
//! The document has the top-level keys first, then one section per schema
//! definition in the order the keys reach them, depth first. An object's
//! keys form a table; any other definition lists the values it accepts.
//! Patterns are shown for keys and list items; a definition's own
//! alternatives show their description instead, since patterns such as the
//! duration's are unreadable.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use serde_json::{Map, Value};

/// Where definitions live and how references name them.
const DEFS_PREFIX: &str = "#/$defs/";

/// Renders the reference for `schema`, a draft 2020-12 JSON Schema whose
/// root is an object and whose definitions are under `$defs`.
///
/// # Errors
///
/// A reference names no definition, or a schema has a shape this renderer
/// does not know, so that a change to the config model cannot drop part of
/// the reference silently.
pub fn render(schema: &Value) -> Result<String, String> {
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let renderer = Renderer { defs: &defs };
    let mut order = Vec::new();
    renderer.collect(schema, &mut order, &mut BTreeSet::new())?;

    let mut out = String::new();
    out.push_str("# Configuration reference\n\n");
    out.push_str(
        "<!-- Generated by `cargo xtask config-docs` from the config file's JSON Schema; do not edit. -->\n\n",
    );
    if let Some(description) = description(schema) {
        let _ = writeln!(out, "{description}\n");
    }
    out.push_str(
        "Each table lists a section's keys with their type and default. A key without a default is optional unless marked **required**. The JSON Schema itself is [`schema/tgin.v1.schema.json`](../schema/tgin.v1.schema.json); `tgin config schema` prints it.\n\n",
    );
    out.push_str("## Top level\n\n");
    out.push_str(&renderer.table(schema)?);
    for name in order {
        let def = &defs[&name];
        let _ = writeln!(out, "\n## `{name}`\n");
        out.push_str(&renderer.definition(def)?);
    }
    Ok(out)
}

struct Renderer<'a> {
    defs: &'a Map<String, Value>,
}

impl Renderer<'_> {
    /// Appends to `order` every definition `schema` reaches, depth first,
    /// each once.
    fn collect(
        &self,
        schema: &Value,
        order: &mut Vec<String>,
        seen: &mut BTreeSet<String>,
    ) -> Result<(), String> {
        let Some(object) = schema.as_object() else {
            return Ok(());
        };
        if let Some(name) = reference(schema)? {
            if seen.insert(name.to_owned()) {
                let def = self.def(name)?;
                order.push(name.to_owned());
                self.collect(def, order, seen)?;
            }
            return Ok(());
        }
        for key in ["properties", "patternProperties"] {
            if let Some(properties) = object.get(key).and_then(Value::as_object) {
                for property in properties.values() {
                    self.collect(property, order, seen)?;
                }
            }
        }
        if let Some(items) = object.get("items") {
            self.collect(items, order, seen)?;
        }
        for key in ["anyOf", "oneOf"] {
            if let Some(alternatives) = object.get(key).and_then(Value::as_array) {
                for alternative in alternatives {
                    self.collect(alternative, order, seen)?;
                }
            }
        }
        Ok(())
    }

    fn def(&self, name: &str) -> Result<&Value, String> {
        self.defs
            .get(name)
            .ok_or_else(|| format!("`{DEFS_PREFIX}{name}` is not defined"))
    }

    /// A definition's section: its description, then its keys, the values
    /// it accepts, or its type.
    fn definition(&self, def: &Value) -> Result<String, String> {
        let mut out = String::new();
        if let Some(description) = description(def) {
            let _ = writeln!(out, "{description}\n");
        }
        let alternatives = ["enum", "const", "oneOf", "anyOf"]
            .iter()
            .any(|key| def.get(key).is_some());
        if def.get("properties").is_some() {
            out.push_str(&self.table(def)?);
        } else if alternatives {
            out.push_str("One of:\n\n");
            for alternative in self.alternatives(def)? {
                let _ = writeln!(out, "- {alternative}");
            }
        } else {
            let _ = writeln!(out, "Type: {}.", self.kind(def, false)?);
        }
        if let Some(examples) = def.get("examples").and_then(Value::as_array) {
            let shown: Vec<String> = examples.iter().map(literal).collect();
            let _ = writeln!(out, "\nExamples: {}.", shown.join(", "));
        }
        Ok(out)
    }

    /// The values a non-object definition accepts, each with its
    /// description.
    fn alternatives(&self, def: &Value) -> Result<Vec<String>, String> {
        if let Some(values) = def.get("enum").and_then(Value::as_array) {
            return Ok(values.iter().map(literal).collect());
        }
        if def.get("const").is_some() {
            return Ok(vec![self.alternative(def)?]);
        }
        let Some(alternatives) = def
            .get("oneOf")
            .or_else(|| def.get("anyOf"))
            .and_then(Value::as_array)
        else {
            return Err(format!(
                "a definition with no keys and no alternatives: {def}"
            ));
        };
        let mut out = Vec::new();
        for alternative in alternatives {
            if let Some(values) = alternative.get("enum").and_then(Value::as_array) {
                // An enum's undocumented values come grouped.
                out.extend(values.iter().map(literal));
            } else {
                out.push(self.alternative(alternative)?);
            }
        }
        Ok(out)
    }

    /// One alternative of a definition: its value or shape, and its
    /// description.
    fn alternative(&self, schema: &Value) -> Result<String, String> {
        let shape = if let Some(value) = schema.get("const") {
            literal(value)
        } else if let Some((key, value)) = tagged(schema) {
            format!("`{key}`: {}", self.kind(value, false)?)
        } else {
            self.kind(schema, false)?
        };
        Ok(match description(schema) {
            Some(description) => format!("{shape} — {description}"),
            None => shape,
        })
    }

    /// The table of an object schema's keys.
    fn table(&self, schema: &Value) -> Result<String, String> {
        let required: BTreeSet<&str> = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|names| names.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
            return Err(format!("an object without properties: {schema}"));
        };
        let mut out = String::from("| Key | Type | Default | Description |\n|---|---|---|---|\n");
        for (key, property) in properties {
            let default = if required.contains(key.as_str()) {
                "**required**".to_owned()
            } else {
                property.get("default").map_or_else(String::new, literal)
            };
            // A key without a description of its own takes its type's.
            let described = description(property).or_else(|| {
                reference(property)
                    .ok()
                    .flatten()
                    .or_else(|| nullable_reference(property))
                    .and_then(|name| self.defs.get(name))
                    .and_then(description)
            });
            let _ = writeln!(
                out,
                "| `{key}` | {} | {} | {} |",
                cell(&self.kind(property, true)?),
                cell(&default),
                cell(&described.unwrap_or_default()),
            );
        }
        Ok(out)
    }

    /// A schema's type in words, with references as links. `patterns` shows
    /// string patterns.
    fn kind(&self, schema: &Value, patterns: bool) -> Result<String, String> {
        if let Some(name) = reference(schema)? {
            self.def(name)?;
            return Ok(format!("[{name}](#{})", name.to_ascii_lowercase()));
        }
        if let Some(value) = schema.get("const") {
            return Ok(literal(value));
        }
        if let Some(values) = schema.get("enum").and_then(Value::as_array) {
            let shown: Vec<String> = values.iter().map(literal).collect();
            return Ok(shown.join(" or "));
        }
        for key in ["anyOf", "oneOf"] {
            if let Some(alternatives) = schema.get(key).and_then(Value::as_array) {
                let mut shown = Vec::new();
                for alternative in alternatives.iter().filter(|a| !is_null(a)) {
                    shown.push(self.kind(alternative, patterns)?);
                }
                return Ok(shown.join(" or "));
            }
        }
        let types: Vec<&str> = match schema.get("type") {
            Some(Value::String(name)) => vec![name.as_str()],
            Some(Value::Array(names)) => names
                .iter()
                .filter_map(Value::as_str)
                .filter(|name| *name != "null")
                .collect(),
            _ => return Err(format!("a schema without a type: {schema}")),
        };
        let [name] = types.as_slice() else {
            return Err(format!("a schema with several types: {schema}"));
        };
        let mut text = match *name {
            "array" => match schema.get("items") {
                Some(items) => format!("list of {}", self.kind(items, patterns)?),
                None => "list".to_owned(),
            },
            "object" => match schema.get("patternProperties").and_then(Value::as_object) {
                Some(keys) => {
                    let [(pattern, value)] = keys.iter().collect::<Vec<_>>()[..] else {
                        return Err(format!("an object with several key patterns: {schema}"));
                    };
                    format!(
                        "map of names matching `{pattern}` to {}",
                        self.kind(value, patterns)?
                    )
                }
                None => "object".to_owned(),
            },
            "string" if schema.get("format").and_then(Value::as_str) == Some("ip") => {
                "IP address".to_owned()
            }
            "string" | "integer" | "boolean" | "number" => (*name).to_owned(),
            other => return Err(format!("an unknown type `{other}`: {schema}")),
        };
        let mut limits = Vec::new();
        if let Some(min) = schema.get("minimum") {
            limits.push(format!("at least {min}"));
        }
        if let Some(max) = schema.get("maximum") {
            limits.push(format!("at most {max}"));
        }
        if schema.get("minLength").and_then(Value::as_u64) == Some(1) {
            limits.push("not empty".to_owned());
        }
        if patterns && let Some(pattern) = schema.get("pattern").and_then(Value::as_str) {
            limits.push(format!("matching `{pattern}`"));
        }
        if !limits.is_empty() {
            let _ = write!(text, " ({})", limits.join(", "));
        }
        Ok(text)
    }
}

/// The definition `schema` refers to, if it is a reference.
fn reference(schema: &Value) -> Result<Option<&str>, String> {
    match schema.get("$ref").and_then(Value::as_str) {
        None => Ok(None),
        Some(target) => target
            .strip_prefix(DEFS_PREFIX)
            .map(Some)
            .ok_or_else(|| format!("a reference outside `$defs`: {target}")),
    }
}

/// The definition of an optional reference, `anyOf: [{$ref}, {type: null}]`.
fn nullable_reference(schema: &Value) -> Option<&str> {
    let alternatives = schema.get("anyOf")?.as_array()?;
    let mut refs = alternatives.iter().filter(|a| !is_null(a));
    let only = refs.next()?;
    if refs.next().is_some() {
        return None;
    }
    reference(only).ok().flatten()
}

fn is_null(schema: &Value) -> bool {
    schema.get("type").and_then(Value::as_str) == Some("null")
}

/// An externally tagged alternative: an object with exactly one key,
/// required.
fn tagged(schema: &Value) -> Option<(&str, &Value)> {
    let properties = schema.get("properties")?.as_object()?;
    let [(key, value)] = properties.iter().collect::<Vec<_>>()[..] else {
        return None;
    };
    let required = schema.get("required")?.as_array()?;
    (required.len() == 1 && required[0].as_str() == Some(key)).then_some((key.as_str(), value))
}

/// A schema's description on one line.
fn description(schema: &Value) -> Option<String> {
    let text = schema.get("description")?.as_str()?;
    Some(text.split_whitespace().collect::<Vec<_>>().join(" "))
}

/// A JSON value as written in YAML, in code style.
fn literal(value: &Value) -> String {
    match value {
        Value::String(text) => format!("`{text}`"),
        other => format!("`{other}`"),
    }
}

/// `text` safe inside a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    fn sample() -> Value {
        json!({
            "title": "sample config",
            "description": "The file.",
            "type": "object",
            "required": ["version"],
            "properties": {
                "version": { "const": 1, "description": "Must be 1." },
                "server": {
                    "anyOf": [{ "$ref": "#/$defs/Server" }, { "type": "null" }]
                },
                "names": {
                    "type": "object",
                    "default": {},
                    "description": "Things, by name.",
                    "patternProperties": { "^[a-z]+$": { "$ref": "#/$defs/Mode" } }
                }
            },
            "$defs": {
                "Server": {
                    "description": "The listener.",
                    "type": "object",
                    "properties": {
                        "listen": {
                            "type": "array",
                            "items": { "type": "string" },
                            "default": ["0.0.0.0:8080"],
                            "description": "Addresses,\nas `ip:port`."
                        },
                        "limit": {
                            "type": "integer",
                            "minimum": 1,
                            "maximum": 100,
                            "default": 10,
                            "description": "A | pipe."
                        },
                        "wait": { "$ref": "#/$defs/Duration", "default": "5s" }
                    }
                },
                "Duration": {
                    "description": "A duration.",
                    "anyOf": [
                        { "type": "string", "pattern": "^[0-9]+s$" },
                        { "type": "integer", "const": 0 }
                    ],
                    "examples": ["5s", 0]
                },
                "Mode": {
                    "oneOf": [
                        { "enum": ["a", "b"], "type": "string" },
                        { "const": "c", "description": "The third." },
                        {
                            "type": "object",
                            "properties": { "pull": { "$ref": "#/$defs/Server" } },
                            "required": ["pull"],
                            "description": "Tagged."
                        }
                    ]
                }
            }
        })
    }

    #[test]
    fn renders_keys_definitions_and_values() {
        let out = render(&sample()).expect("renders");
        let expected = "# Configuration reference

<!-- Generated by `cargo xtask config-docs` from the config file's JSON Schema; do not edit. -->

The file.

Each table lists a section's keys with their type and default. A key without a default is optional unless marked **required**. The JSON Schema itself is [`schema/tgin.v1.schema.json`](../schema/tgin.v1.schema.json); `tgin config schema` prints it.

## Top level

| Key | Type | Default | Description |
|---|---|---|---|
| `names` | map of names matching `^[a-z]+$` to [Mode](#mode) | `{}` | Things, by name. |
| `server` | [Server](#server) |  | The listener. |
| `version` | `1` | **required** | Must be 1. |

## `Mode`

One of:

- `a`
- `b`
- `c` — The third.
- `pull`: [Server](#server) — Tagged.

## `Server`

The listener.

| Key | Type | Default | Description |
|---|---|---|---|
| `limit` | integer (at least 1, at most 100) | `10` | A \\| pipe. |
| `listen` | list of string | `[\"0.0.0.0:8080\"]` | Addresses, as `ip:port`. |
| `wait` | [Duration](#duration) | `5s` | A duration. |

## `Duration`

A duration.

One of:

- string
- `0`

Examples: `5s`, `0`.
";
        assert_eq!(out, expected);
    }

    #[test]
    fn unknown_reference_is_an_error() {
        let schema = json!({
            "type": "object",
            "properties": { "a": { "$ref": "#/$defs/Missing" } }
        });
        let err = render(&schema).expect_err("missing definition");
        assert!(err.contains("Missing"), "{err}");
    }

    #[test]
    fn unknown_shape_is_an_error() {
        let schema = json!({
            "type": "object",
            "properties": { "a": { "description": "no type" } }
        });
        assert!(render(&schema).is_err());
    }

    /// Every definition of the real schema gets a section, and every key of
    /// every object a row.
    #[test]
    fn real_schema_is_complete() {
        let schema: Value =
            serde_json::from_str(&tgin_core::config::schema()).expect("the schema is JSON");
        let out = render(&schema).expect("renders");
        let defs = schema["$defs"].as_object().expect("definitions");
        for (name, def) in defs {
            assert!(out.contains(&format!("\n## `{name}`\n")), "{name} missing");
            for key in def
                .get("properties")
                .and_then(Value::as_object)
                .into_iter()
                .flat_map(|p| p.keys())
            {
                assert!(
                    out.contains(&format!("| `{key}` |")),
                    "{name}.{key} missing"
                );
            }
        }
        for key in schema["properties"].as_object().expect("keys").keys() {
            assert!(out.contains(&format!("| `{key}` |")), "{key} missing");
        }
    }
}
